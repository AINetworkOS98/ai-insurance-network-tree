import asyncio, edge_tts, os
VOICE = "th-TH-PremwadeeNeural"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out", "audio")
LINES = {
 "vo1": "ธุรกิจประกันชีวิตยุคใหม่ เริ่มต้นจากการสร้างทีมให้เติบโตอย่างเป็นระบบ",
 "vo2": "โครงสร้างหนึ่งต่อห้า วางหัวหน้าทีมไว้ด้านบน เชื่อมโยงสมาชิกห้าคน และขยายเครือข่ายออกไปเป็นชั้น ๆ อย่างเป็นระเบียบ",
 "vo3": "เห็นภาพรวมทีมได้ชัดเจน ทั้งรายชื่อสมาชิก สถานะการติดตามงาน และข้อมูลผู้มุ่งหวัง ติดตามงานอย่างเป็นระบบ ลดงานที่ตกหล่น",
 "vo4": "เปลี่ยนงานซ้ำ ๆ ให้เป็นระบบ ด้วยผู้ช่วย AI ที่ช่วยวิเคราะห์และจัดลำดับการติดตาม โดยตัวแทนยังเป็นผู้ตัดสินใจในเรื่องสำคัญ",
 "vo5": "เริ่มต้นสร้างระบบทีมประกันชีวิตของคุณ ด้วยระบบ หนึ่งต่อห้า ออโตไพลอท",
}
async def main():
    for name, text in LINES.items():
        await edge_tts.Communicate(text, VOICE, rate="-6%", pitch="-2Hz").save(os.path.join(OUT, name + ".mp3"))
        print("saved", name)
asyncio.run(main())
