export const RIDER_CATS = ['สัญญาเพิ่มเติม', 'เฮลท์', 'PA', 'โรคร้าย'];

export function isRiderCat(cat: string): boolean {
  return RIDER_CATS.includes(cat);
}

/**
 * แยก "สัญญาหลัก" กับ "อนุสัญญา/สัญญาเพิ่มเติม" จากตัวสินค้าจริง (ไม่ดูแค่หมวด)
 * เหตุผล: หมวด "LifeVerse" (รหัส LV-*) มีทั้งสัญญาหลักและสัญญาเพิ่มเติมปนกัน
 *   สัญญาหลัก: LV-อ01 (อ.1/ขจ.1) · LV-อ02 · LV-A03 (อ.3) · LV-สร2 · LV-D11 (มัลติเพย์) · LV-D28 (กร.48)
 *   อนุสัญญา:  LV-รพ (ค่ารักษา/รายวัน) · LV-OP4 (ผู้ป่วยนอก) · LV-HHA/LV-NHG/LV-SPH/LV-VP (เฮลท์ ฟิต)
 *              · LV-C21 (มัลติเพย์ แคนเซอร์)
 * ⇒ ตรวจจากชื่อ/รหัสด้วยคีย์เวิร์ด เพื่อไม่ให้ "อนุสัญญา" หลุดไปอยู่ในลิสต์สัญญาหลัก
 */
const RIDER_NAME_RE = /(ค่ารักษา|ผู้ป่วยนอก|เวชภัณฑ์|เฮลท์|health|แคนเซอร์|มะเร็ง|โรคร้าย|อุบัติเหตุ|ทุพพลภาพ|รายวัน|ชดเชย|สัญญาเพิ่มเติม)/i;
const RIDER_CODE_RE = /^LV-(รพ|OP\d*|HHA|NHG|SPH|VP|C\d+)$/i;

export function isRiderProduct(p: { c?: string | null; n?: string | null; cat?: string | null } | null | undefined): boolean {
  if (!p) return false;
  const code = String(p.c || '');
  const name = String(p.n || '');
  const cat = String(p.cat || '');
  if (isRiderCat(cat)) return true;
  // หมวด LifeVerse (LV-*) ทั้งหมด = อนุสัญญา/สัญญาเพิ่มเติม (ตามที่เจ้าของระบบยืนยัน)
  if (cat === 'LifeVerse') return true;
  if (/^LV-/i.test(code)) return true;
  if (/^LV\b/i.test(name)) return true;
  if (RIDER_CODE_RE.test(code)) return true;
  if (RIDER_NAME_RE.test(name)) return true;
  return false;
}

export function templateFor(cat: string): CategoryTemplate {
  return CATEGORY_TEMPLATES[cat] || FALLBACK_TEMPLATE;
}

function inRange(v: number, r?: [number, number | null]): boolean {
  if (!r) return true;
  if (r[0] != null && v < r[0]) return false;
  if (r[1] != null && v > r[1]) return false;
  return true;
}

function num(n?: number | null) {
  return n == null ? '' : Number(n).toLocaleString('th-TH');
}

function payText(pay?: [number, number]) {
  if (!pay) return '';
  const [a, b] = pay;
  if (a == null || b == null) return '';
  if (a <= 0) return `ชำระเบี้ยไม่เกิน ${b} ปี`;
  if (b >= 90) return `ชำระเบี้ยตั้งแต่ ${a} ปีขึ้นไป`;
  return `ชำระเบี้ย ${a}–${b} ปี`;
}

function capText(cap?: [number, number | null]) {
  if (!cap) return '';
  const [a, b] = cap;
  if (b == null) return `ทุน ${num(a)} ขึ้นไป`;
  if (a == null || a <= 0) return `ทุนไม่เกิน ${num(b)}`;
  return `ทุน ${num(a)}–${num(b)}`;
}

export function condText(v?: Variant | null): string {
  if (!v) return '-';
  return [
    v.a ? `อายุ ${v.a[0]}–${v.a[1]}` : '',
    capText(v.cap),
    payText(v.pay),
    v.pl ? `แผน ${v.pl}` : '',
    v.note || '',
  ].filter(Boolean).join(' • ') || '-';
}

export type ProjectSample = {
  no: number;
  code: string;
  name: string;
  cat: string;
  gender: 'ชาย' | 'หญิง';
  age: number;
  ageAdjusted: boolean;
  cover: number;
  rider: boolean;
  variant: Variant | null;
  cond: string;
  goal: string;
  structure: string[];
  benefits: string[];
  cashback: CashbackInfo;
  payYears: number;
  payAssumed: boolean;
};

// เลือกเงื่อนไขที่ตรงกับอายุ/ทุนในตารางจริง (ถ้าอายุที่ต้องการไม่อยู่ในเกณฑ์ → ขยับไปอายุที่เข้าเกณฑ์ใกล้สุด)
function pickVariant(variants: Variant[], age: number, cover: number) {
  if (!variants.length) return { variant: null as Variant | null, age };
  const exact = variants.filter(v => inRange(age, v.a));
  if (exact.length) {
    const scored = [...exact].sort((x, y) => score(y, cover) - score(x, cover));
    return { variant: scored[0], age };
  }
  // หาอายุที่เข้าเกณฑ์ใกล้สุด
  const lows = variants.map(v => v.a?.[0]).filter((n): n is number => typeof n === 'number');
  const highs = variants.map(v => v.a?.[1]).filter((n): n is number => typeof n === 'number');
  let adjusted = age;
  if (lows.length && Math.min(...lows) > age) adjusted = Math.min(...lows);
  else if (highs.length && Math.max(...highs) < age) adjusted = Math.max(...highs);
  const fit = variants.filter(v => inRange(adjusted, v.a));
  const scored = [...(fit.length ? fit : variants)].sort((x, y) => score(y, cover) - score(x, cover));
  return { variant: scored[0] || null, age: adjusted };
}

function score(v: Variant, cover: number) {
  let s = 0;
  if (inRange(cover, v.cap)) s += 4;
  if (v.pay) s += 1;
  if (v.y2 != null) s += 1;
  return s;
}

// จำนวนปีชำระเบี้ยสำหรับ "ภาพการจ่ายเบี้ย" — ใช้ช่วงปีชำระจากตารางก่อน (แม่นสุด)
// แล้วค่อยเดาจากชื่อแบบ (เช่น 20/20, 15/5) ถ้าตารางไม่ระบุ; ถ้าไม่รู้จริงใช้ 10 ปี และติดป้ายว่าสมมติ
export function payYearsOf(p: { n: string; v?: Variant[] }, v: Variant | null): { years: number; assumed: boolean } {
  if (v?.pay) {
    const hi = v.pay[1];
    const lo = v.pay[0];
    if (hi != null && hi >= 1 && hi <= 40) return { years: Math.max(1, hi), assumed: false };
    if (hi != null && hi > 40 && lo != null && lo >= 1 && lo <= 40) return { years: lo, assumed: false };
  }
  const m = p.n.match(/\/\s*(\d{1,2})(?!\d)/);
  if (m) {
    const y = Number(m[1]);
    if (y >= 1 && y <= 40) return { years: y, assumed: false };
  }
  return { years: 10, assumed: true };
}

export function buildProjectSamples(
  products: Product[],
  opts: { startGender?: 'ชาย' | 'หญิง'; age?: number; cover?: number } = {}
): ProjectSample[] {
  const startGender = opts.startGender || 'ชาย';
  const wantAge = opts.age && opts.age > 0 ? opts.age : 30;
  const cover = opts.cover && opts.cover > 0 ? opts.cover : 1000000;
  return products.map((p, i) => {
    const tpl = templateFor(p.cat);
    const { variant, age } = pickVariant(p.v || [], wantAge, cover);
    const rider = tpl.rider === true;
    const pay = payYearsOf(p, variant);
    return {
      no: i + 1,
      code: p.c,
      name: p.n,
      cat: p.cat,
      gender: (i % 2 === 0 ? startGender : startGender === 'ชาย' ? 'หญิง' : 'ชาย') as 'ชาย' | 'หญิง',
      age,
      ageAdjusted: age !== wantAge,
      cover,
      rider,
      variant,
      cond: condText(variant),
      goal: tpl.goal,
      structure: tpl.structure,
      benefits: [...tpl.benefits, ...(EXTRA_BENEFITS[p.cat] || [])],
      cashback: cashbackFor(p.cat),
      payYears: pay.years,
      payAssumed: pay.assumed,
    };
  });
}
