/** ข้อความสรุปทั้งกระบวนการ — ใช้กับปุ่ม "คัดลอกกระบวนการทั้งหมด" */
export function workflowPlainText(): string {
  const head = [
    'กระบวนการทำงานอัตโนมัติ — AI Insurance Network Tree',
    'ระบบ: รับข้อมูล → บันทึกพร้อมกัน → คิวทนทาน → Worker → n8n → แจ้งเตือน → ตำแหน่ง/รายได้ → Audit Log',
    '',
  ];
  const body = WORKFLOW_STEPS.map(s => [
    `${s.n}. ${s.icon} ${s.title}`,
    `   ผู้ทำงาน: ${s.actor}`,
    `   อยู่ที่: ${s.where}`,
    ...(s.api ? [`   API/ข้อมูล: ${s.api}`] : []),
    ...s.detail.map(d => `   • ${d}`),
    '   ทำตามเพื่อสร้างระบบของคุณ:',
    ...s.repeat.map(r => `     - ${r}`),
    '',
  ].join('\n'));
  return head.concat(body).join('\n');
}
